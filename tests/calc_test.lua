local ns = newNamespace()
loadAddonFile("Calc.lua", ns)
local Calc = ns.Calc

test("percent", function()
  eq(Calc.percent(50, 200), 25)
  eq(Calc.percent(5, 0), 0)
  eq(Calc.percent(300, 200), 100)
  eq(Calc.percent(nil, 100), 0)
end)

test("remaining", function()
  eq(Calc.remaining(50, 200), 150)
  eq(Calc.remaining(250, 200), 0)
  eq(Calc.remaining(1, 0), 0)
end)

test("fraction", function()
  eq(Calc.fraction(50, 200), 0.25)
  eq(Calc.fraction(0, 200), 0)
  eq(Calc.fraction(500, 200), 1)
  eq(Calc.fraction(10, 0), 0)
end)

test("xpDelta within a level, across a level-up, and wrap without flag", function()
  eq(Calc.xpDelta(100, 1000, 250, false), 150)
  eq(Calc.xpDelta(900, 1000, 50, true), 150)
  eq(Calc.xpDelta(900, 1000, 50, false), 150)
  eq(Calc.xpDelta(100, 1000, 100, false), 0)
  eq(Calc.xpDelta(10, 100, 15, true), 105)
end)

test("xpPerHour needs a minute of data and some gain", function()
  eq(Calc.xpPerHour(1000, 1800), 2000)
  eq(Calc.xpPerHour(1000, 30), nil)
  eq(Calc.xpPerHour(0, 3600), nil)
  eq(Calc.xpPerHour(nil, 3600), nil)
end)

test("timeToLevel", function()
  eq(Calc.timeToLevel(5000, 2500), 7200)
  eq(Calc.timeToLevel(5000, nil), nil)
  eq(Calc.timeToLevel(5000, 0), nil)
end)

test("killsToLevel rounds up and guards bad input", function()
  eq(Calc.killsToLevel(1000, 90), 12)
  eq(Calc.killsToLevel(1000, nil), nil)
  eq(Calc.killsToLevel(1000, 0), nil)
  eq(Calc.killsToLevel(0, 90), 0)
end)

test("average", function()
  eq(Calc.average({ 2, 4, 6 }), 4)
  eq(Calc.average({}), nil)
  eq(Calc.average(nil), nil)
end)

test("paceDelta", function()
  eq(Calc.paceDelta(6000, 5000), 20)
  eq(Calc.paceDelta(4000, 5000), -20)
  eq(Calc.paceDelta(nil, 5000), nil)
  eq(Calc.paceDelta(5000, 0), nil)
end)

test("cycle wraps and recovers from unknown values", function()
  local v = { "a", "b", "c" }
  eq(Calc.cycle(v, "a", 1), "b")
  eq(Calc.cycle(v, "c", 1), "a")
  eq(Calc.cycle(v, "a", -1), "c")
  eq(Calc.cycle(v, "zzz", 1), "a")
  eq(Calc.cycle({ 320, 400, 480 }, 400, 1), 480)
end)

test("formatNumber plain", function()
  eq(Calc.formatNumber(12340, { thousands = "," }), "12,340")
  eq(Calc.formatNumber(1234567, { thousands = " " }), "1 234 567")
  eq(Calc.formatNumber(0), "0")
  eq(Calc.formatNumber(nil), "0")
  eq(Calc.formatNumber(999, { thousands = "," }), "999")
  eq(Calc.formatNumber(1000, { thousands = "," }), "1,000")
end)

test("formatNumber abbreviated", function()
  eq(Calc.formatNumber(12340, { abbreviated = true }), "12.3k")
  eq(Calc.formatNumber(12340, { abbreviated = true, decimal = "," }), "12,3k")
  eq(Calc.formatNumber(1500000, { abbreviated = true }), "1.5m")
  eq(Calc.formatNumber(1000, { abbreviated = true }), "1k")
  eq(Calc.formatNumber(2000000, { abbreviated = true }), "2m")
  eq(Calc.formatNumber(999, { abbreviated = true }), "999")
end)

test("formatDuration", function()
  eq(Calc.formatDuration(0), "0s")
  eq(Calc.formatDuration(45), "45s")
  eq(Calc.formatDuration(252), "4m 12s")
  eq(Calc.formatDuration(65), "1m 05s")
  eq(Calc.formatDuration(3600), "1h 00m")
  eq(Calc.formatDuration(3900), "1h 05m")
  eq(Calc.formatDuration(183600), "2d 3h")
  eq(Calc.formatDuration(nil), nil)
  eq(Calc.formatDuration(3900, { d = "j", h = "h", m = "min", s = "s" }), "1h 05min")
end)

test("bar targets: fill, quest and rested segments as fractions of the bar", function()
  local snap = { xp = 500, xpMax = 1000, rested = 200, quests = { total = 100 } }
  eq(Calc.barTargets(snap, { showQuestSegment = true, showRestedSegment = true }),
    { fill = 0.5, quest = 0.6, rested = 0.7 })
end)

test("bar targets: hidden segments collapse onto the fill", function()
  local snap = { xp = 500, xpMax = 1000, rested = 200, quests = { total = 100 } }
  eq(Calc.barTargets(snap, { showQuestSegment = false, showRestedSegment = false }),
    { fill = 0.5, quest = 0.5, rested = 0.5 })
end)

test("bar targets: no quest data and a full bar", function()
  eq(Calc.barTargets({ xp = 900, xpMax = 1000, rested = 500 }, { showQuestSegment = true, showRestedSegment = true }),
    { fill = 0.9, quest = 0.9, rested = 1 })
end)

test("the shorter of the rested and quest segments is drawn on top", function()
  eq(Calc.topSegment({ fill = 0.5, quest = 0.6, rested = 0.55 }), "rested")
  eq(Calc.topSegment({ fill = 0.5, quest = 0.6, rested = 0.8 }), "quest")
  eq(Calc.topSegment({ fill = 0.5, quest = 0.5, rested = 0.7 }), "quest")
end)
